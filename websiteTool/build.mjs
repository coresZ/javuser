#!/usr/bin/env node
/**
 * 网页对象工具库 — 构建脚本
 * 将 src/ 模块与 styles/*.css 按顺序拼成可安装的油猴脚本 dist/*.user.js
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = __dirname;
const DIST = path.join(ROOT, "dist");

// 版本号唯一来源是 package.json；PPK_VERSION 仅用于临时覆盖（CI / 发布前试构建）。
// 之前这里写死默认值 "0.4.3"，与 package.json / meta.header.js 各自独立，容易三家不一致。
const PKG = JSON.parse(fs.readFileSync(path.join(__dirname, "package.json"), "utf8"));
const VERSION = process.env.PPK_VERSION || PKG.version;

/** 模块加载顺序（共享作用域 IIFE，运行时依赖靠声明先后 + 函数调用时机） */
const MODULES = [
  "src/config.js",
  "src/utils/gm.js",
  "src/ui/styles.gen.js", // 由 CSS 生成
  "src/ui/host.js",
  "src/ui/theme.js",
  "src/core/actionRegistry.js",
  "src/core/RulesManager.js",
  "src/core/ruleEngine.js",
  "src/core/pickerState.js",
  "src/utils/dom.js",
  "src/ui/PopupPanel.js",
  "src/core/extractor.js",
  "src/core/executeRule.js",
  "src/utils/targetType.js",
  "src/ui/Toolbar.js",
  "src/utils/selector.js",
  "src/ui/ElementPicker.js",
  "src/ui/RulesPanel.js",
  "src/main.js",
];

function read(rel) {
  return fs.readFileSync(path.join(ROOT, rel), "utf8");
}

function write(rel, content) {
  const abs = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content, "utf8");
}

/** 把 CSS 文件变成 JS 字符串常量 */
function generateStylesModule() {
  const names = ["default", "page", "refine"];
  const parts = names.map((name) => {
    const css = fs.readFileSync(path.join(ROOT, "styles", `${name}.css`), "utf8");
    return `var style_${name} = ${JSON.stringify(css)};`;
  });
  const code =
    "// AUTO-GENERATED by build.mjs — do not edit\n" +
    parts.join("\n") +
    "\n";
  write("src/ui/styles.gen.js", code);
  return code;
}

function indentBody(code) {
  return code
    .split("\n")
    .map((line) => (line.length ? "  " + line : line))
    .join("\n");
}

function buildHeader(baseHeader) {
  // 同步 version 字段
  return baseHeader.replace(
    /@version\s+\S+/,
    `@version       ${VERSION}`
  );
}

function build() {
  generateStylesModule();

  let header = read("meta.header.js");
  header = buildHeader(header);

  const chunks = [];
  for (const mod of MODULES) {
    const abs = path.join(ROOT, mod);
    if (!fs.existsSync(abs)) {
      throw new Error(`Missing module: ${mod}`);
    }
    let body = read(mod).replace(/\s+$/, "");
    chunks.push(`\n  // --- ${mod} ---\n` + indentBody(body));
  }

  const out =
    header.trimEnd() +
    "\n\n" +
    "(() => {\n" +
    chunks.join("\n") +
    "\n})();\n";

  const outName = "网页对象工具库.user.js";
  const outPath = path.join(DIST, outName);
  fs.mkdirSync(DIST, { recursive: true });
  fs.writeFileSync(outPath, out, "utf8");

  const bytes = Buffer.byteLength(out, "utf8");
  console.log(`✓ built ${outName}`);
  console.log(`  version: ${VERSION}`);
  console.log(`  size:    ${(bytes / 1024).toFixed(1)} KB`);
  console.log(`  modules: ${MODULES.length}`);
  console.log(`  path:    ${outPath}`);
}

build();
